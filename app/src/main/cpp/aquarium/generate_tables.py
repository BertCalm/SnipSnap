#!/usr/bin/env python3
"""Generate fixed native tables from canonical parameter/preset JSON.

No JSON parser runs on the native audio thread. --check verifies retained output.
The source ordering of parameters.json is the v1 snapshot/wire ordering.
"""
from pathlib import Path
import argparse,json,math
root=Path(__file__).resolve().parent
metadata=json.loads((root/'parameters.json').read_text())
presets=json.loads((root/'presets.json').read_text())
assert len(metadata)==52
assert list(presets)==['dry','fathom','drift','tide','reef','surface','biolume','depth','motion','color','full']
def number(v):
    assert math.isfinite(v)
    s=format(v,'.9g')
    return s+('' if '.' in s or 'e' in s.lower() else '.0')+'f'
lines=['// SPDX-License-Identifier: MIT','// Generated by generate_tables.py. Edit parameters.json/presets.json, then regenerate.','constexpr std::array<ParameterInfo, kParameterCount> kParameterInfo = {{']
for name,p in metadata.items():
    assert p['min']<=p['default']<=p['max']
    assert p.get('step',0) in (0,1)
    if p.get('step',0):assert (p['default']-p['min'])/p['step'] == int((p['default']-p['min'])/p['step'])
    lines.append(f'    {{"{name}", {number(p["min"])}, {number(p["max"])}, {number(p["default"])}, {number(p.get("step",0))}}},')
lines+=['}};','constexpr std::array<std::string_view, kPresetCount> kPresetNames = {{', '    '+', '.join('"'+name+'"' for name in presets),' }};','constexpr std::array<std::array<float, kParameterCount>, kPresetCount> kPresetValues = {{']
for name,overrides in presets.items():
    assert all(k in metadata and math.isfinite(v) and metadata[k]['min']<=v<=metadata[k]['max'] for k,v in overrides.items())
    lines.append('    {{'+', '.join(number(overrides.get(k,p['default'])) for k,p in metadata.items())+'}}, // '+name)
lines+=['}};','']
expected='\n'.join(lines)
parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
path=root/'private/ParameterTables.inc'
if args.check:
    if not path.exists() or path.read_text()!=expected:raise SystemExit('Aquarium generated parameter tables are stale; run generate_tables.py')
else:path.write_text(expected)
