const {chromium}=require('playwright');
(async()=>{
 const browser=await chromium.launch({executablePath:process.env.BRISTLE_CHROMIUM||'/usr/bin/chromium',headless:true,args:['--no-sandbox']});
 const page=await browser.newPage({viewport:{width:1100,height:900}});let errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.goto(process.argv[2]||'http://127.0.0.1:8766/listen.html');
 if(await page.locator('#keys button').count()!==13)throw Error('key count');
 await page.locator('#keys button').nth(0).click();
 await page.waitForFunction(()=>current!==null && ctx.state==='running');
 if(await page.evaluate(()=>current.source.buffer.duration)!==1)throw Error('native duration');
 await page.locator('#stop').click();
 if(!await page.evaluate(()=>current===null))throw Error('stop failed');
 await page.selectOption('#route','B');await page.selectOption('#touch','0');
 await page.locator('#keys button').nth(12).click();
 await page.waitForFunction(()=>current!==null && decoded.has('B_48_0'));
 await page.locator('h1').click();
 for(const key of ['a','w','s','e','d'])await page.keyboard.press(key);
 await page.waitForFunction(()=>current!==null && decoded.has('B_40_0'));
 await page.locator('#stop').click();
 if(await page.locator('#status').textContent())throw Error('audio error');
 if(process.argv[3])await page.screenshot({path:process.argv[3],fullPage:true});
 await page.setViewportSize({width:390,height:844});
 if(!await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth))throw Error('mobile overflow');
 await page.locator('#keys button').nth(5).click();
 await page.waitForFunction(()=>current!==null);
 await page.locator('#stop').click();
 if(errors.length)throw Error(errors.join('\n'));
 console.log('PASS: desktop/mobile layout, audio unlock, native buffers, route/touch selection, rapid retriggers, stop, no page errors. Audio not heard.');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
