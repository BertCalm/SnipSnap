"""Export coarse model coefficients and authored events, never reference PCM."""
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[3]
model=json.loads((ROOT/'prototype/footwork/tap_contact_fit/model.json').read_text())
report=json.loads((Path(__file__).parent/'report.json').read_text())
roles={'toe':0,'heel':1,'brush':2,'spank':3,'shuffle_brush':4,'shuffle_spank':5}
def arr(x):return 'doubleArrayOf('+','.join(repr(float(a)) for a in x)+')'
lines=['package com.snipsnap.synth','','/** Generated by prototype/footwork/tap_connected/native_data.py; numeric fits, no PCM. */','internal object FootworkTapData {',f'    const val GAIN = {model["gain"]}']
lines+=['    val frequencies = '+arr(model['voices']['toe']['frequency_hz']),
        '    val spectra = arrayOf('+','.join(arr(model['voices'][v]['amplitude_db']) for v in ['toe','heel'])+')',
        '    val envelopes = arrayOf('+','.join(arr(model['voices'][v]['envelope']) for v in ['toe','heel'])+')']
from scipy import signal
lines+=['    val brushFilter = arrayOf('+','.join(arr(c) for c in signal.butter(2,[330,7200],fs=176400,btype='bandpass',output='sos'))+')']
lines+=['    data class Event(val seconds: Double, val role: Int, val force: Double, val right: Boolean, val travel: Double)',
        '    data class Plan(val seconds: Double, val events: List<Event>)','    val plans = mapOf(']
for name,p in report['plans'].items():
    events=','.join(f'Event({e["seconds"]},{roles[e["role"]]},{float(e["force"])},{str(e["foot"]=="R").lower()},{float(e["travel"])})' for e in p['events'])
    lines.append(f'        "{name}" to Plan({p["duration"]},listOf({events})),')
lines+=['    )','}']
(ROOT/'synth/src/main/kotlin/com/snipsnap/synth/FootworkTapData.kt').write_text('\n'.join(lines)+'\n')
