"""Writes synth/.../KindredRecipes.kt from the prototype's kit table, so the Kotlin pads are the
pads the owner heard at round 2, number for number (no hand transcription)."""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import kindred_kits as kk

ROLE = {"kick": "KICK", "snare": "SNARE", "clap": "CLAP", "hatClosed": "HAT_CLOSED", "hatOpen": "HAT_OPEN", "tom": "TOM", "perc": "PERC"}
INT = {"w1", "w2", "hp", "sync"}

def num(k, v):
    if k in INT: return str(int(v))
    s = repr(float(v))
    return s

rows = []
for kit, K in kk.KITS.items():
    for i, p in enumerate(K["pads"]):
        base = kk.BASE[p["base"]]
        over = {k: v for k, v in p["params"].items() if k != "burst" and base.get(k) != v}
        mac = {k: v for k, v in p["mac"].items() if v != .5}
        shape = ", ".join(f"{k} = {num(k, v)}" for k, v in over.items())
        macs = ", ".join(f'"{k}" to {float(v)}f' for k, v in mac.items())
        rows.append(f'        Recipe("{kit}_A{i + 1:02d}", "{p["name"]}", KindredVoice.{p["base"]}, KindredRole.{ROLE[p["cls"]]}, '
                    f'mapOf({macs}), {float(p["mix"])}f)' + (f" {{ it.copy({shape}) }}" if shape else ""))
src = f'''package com.snipsnap.synth

/**
 * KINDRED's pad recipes: the 56 one-shots of the four genre kits the owner accepted at round 2 (2026-11-15).
 *
 * Generated by `prototype/kindred/gen_recipes_kt.py` from the prototype's kit table, so every number is the one
 * that was heard; regenerate rather than edit by hand. A recipe is a voice, the role it plays (model 2's voicing
 * reads it), the pad's macros, its groove mix level, and the circuit settings it changes from its voice. A saved
 * [KindredPatch] names its recipe, so a kit pad replays byte for byte.
 */
object KindredRecipes {{

    class Recipe(
        val id: String,
        val name: String,
        val voice: KindredVoice,
        val role: KindredRole,
        val macros: Map<String, Float>,
        /** The pad's level in its kit's groove (the prototype's `mix`). */
        val mix: Float,
        val shape: (Kindred.Shape) -> Kindred.Shape = {{ it }},
    )

    val ALL: List<Recipe> = listOf(
{",\n".join(rows)},
    )

    private val BY_ID = ALL.associateBy {{ it.id }}

    fun byId(id: String): Recipe = BY_ID[id] ?: throw IllegalArgumentException("no KINDRED recipe $id")

    fun has(id: String): Boolean = id in BY_ID
}}
'''
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "synth", "src", "main", "kotlin", "com", "snipsnap", "synth", "KindredRecipes.kt")
open(out, "w").write(src)
print(len(rows), "recipes")
