"""Writes TerraSticksTables.kt from the fitted prototype models, and a v=1 reference WAV per
stroke so the Kotlin render can be checked against the Python one.
Usage: gen_kotlin.py <models.pkl> <out.kt> <ref_wav_dir>"""
import sys, os, pickle, numpy as np
import fit as F
SR = F.SR
models = pickle.load(open(sys.argv[1], "rb")); out_kt, refdir = sys.argv[2], sys.argv[3]; os.makedirs(refdir, exist_ok=True)
TIMES = [1, 5, 9, 25, 27, 33, 38, 42, 47, 53, 65, 80, 96, 104, 133, 143, 158, 162, 174, 180, 184]
LEVELS = [.26, .46, .59, .55, .5, .72, .52, .55, .69, .49, .61, .48, .33, .29, .38, .2, .29, .29, .08, .06, .08]

def simple(name, secs):
    m = models[name]; y = F.render(m, secs); pk = float(np.max(np.abs(y)))
    c = np.array(m["coef"]).reshape(-1, 2) / pk
    return dict(width=m["width_ms"], rise=m.get("rise_ms", 0.0), hz=[p[0] for p in m["partials"]], t60=[p[2] for p in m["partials"]],
                hits=[dict(time=0.0, sin=c[:, 0], cos=c[:, 1], bands=[[lo, hi, a / pk, T] for lo, hi, a, T in m["bands"]])]), y / pk

def clapper():
    m = models["CLAPPER_SLAT"]; hz = [p[0] for p in m["partials"]]; c = np.array(m["coef"]).reshape(-1, 2); hits = []
    for ms, lv in zip(TIMES, LEVELS):
        u = min(1.0, lv / 0.72)                    # a quieter slat click is also a duller one (the prototype's velocity law, baked in)
        g = np.array([u ** min(3.0, 1.0 + 0.45 * np.log2(h / hz[0])) for h in hz])
        hits.append(dict(time=ms * 1e-3, sin=c[:, 0] * g, cos=c[:, 1] * g, bands=[[lo, hi, a * u ** F.band_exponent(lo), T] for lo, hi, a, T in m["bands"]]))
    s = dict(width=m["width_ms"], rise=0.0, hz=hz, t60=[p[2] for p in m["partials"]], hits=hits)
    return s

def cowbell():
    m = models["COWBELL_R5"]; n = len(m["notes"]); c = np.array(m["coef"]).reshape(len(m["strikes"]), n, 2)
    hits = [dict(time=ts, sin=c[k, :, 0], cos=c[k, :, 1], bands=[b for b in m["bursts"][k] if b[2] > 1e-5]) for k, ts in enumerate(m["strikes"])]
    return dict(width=0.0, rise=0.3, hz=[q[0] for q in m["notes"]], t60=[q[1] for q in m["notes"]], hits=hits)

def py_render(s, secs):
    """The stroke table rendered plainly at 44.1 kHz (v = 1, take 0): what the Kotlin must reproduce."""
    n = int(secs * SR); t = np.arange(n) / SR; y = np.zeros(n); parts = np.zeros(n)
    for hi_, h in enumerate(s["hits"]):
        tt = np.maximum(t - h["time"], 0.0); on = t >= h["time"]
        bloom = (1 - np.exp(-tt / (s["rise"] * 1e-3))) if s["rise"] > 0 else 1.0
        for hz, T, a, b in zip(s["hz"], s["t60"], h["sin"], h["cos"]):
            parts += np.exp(-6.9078 * tt / T) * on * bloom * (a * np.sin(2 * np.pi * hz * tt) + b * np.cos(2 * np.pi * hz * tt))
        for i, (lo, hi, a, T) in enumerate(h["bands"]):
            y += a * F.band_noise(lo, hi, n, 31 * i + 977 * hi_) * np.exp(-6.9078 * tt / T) * on
    if s["width"] > 0: parts = np.convolve(parts, F.contact(s["width"]))[:n]
    return y + parts

SECS = {"ODAIKO_A": 1.45, "ODAIKO_B": 1.45, "NAGADO": 1.2, "SHIME": 0.8, "SHIME_B": 0.8, "KA": 0.5, "KANE": 1.0, "KANE_EDGE": 1.0, "CHAPPA": 1.45, "WATER": 0.8}
strokes = {}
for name, secs in SECS.items(): strokes[name], _ = simple(name, secs)
strokes["CLAPPER"] = clapper(); strokes["COWBELL"] = cowbell()
# the fan (round 7): its gestures are fitted directly as stroke tables
for fan in ("FAN", "FAN_SWEEP"):
    if fan + "_STROKE" in models: strokes[fan] = {k: (v if k != "hits" else [dict(h) for h in v]) for k, v in models[fan + "_STROKE"].items()}
for name in [n for n in ("CLAPPER", "COWBELL", "FAN", "FAN_SWEEP") if n in strokes]:       # level these to a unit peak as well
    pk = float(np.max(np.abs(py_render(strokes[name], 1.45 if name == "COWBELL" else 0.5))))
    for h in strokes[name]["hits"]:
        h["sin"] = np.array(h["sin"]) / pk; h["cos"] = np.array(h["cos"]) / pk; h["bands"] = [[lo, hi, a / pk, T] for lo, hi, a, T in h["bands"]]
for name, s in strokes.items():
    F.writewav(f"{refdir}/{name}.wav", np.clip(py_render(s, SECS.get(name, 1.45 if name == "COWBELL" else 0.5)) * 0.9, -1, 1))

d = lambda xs: "doubleArrayOf(" + ", ".join(f"{float(x):.6g}" if abs(float(x)) >= 1e-9 else "0.0" for x in xs) + ")"
fix = lambda t: t if ("." in t or "e" in t) else t + ".0"
def dd(xs): return "doubleArrayOf(" + ", ".join(fix(f"{float(x):.6g}") if abs(float(x)) >= 1e-9 else "0.0" for x in xs) + ")"
L = ["package com.snipsnap.synth", "",
     "/**", " * The fitted tables [TerraSticks] plays: generated by `prototype/taiko/gen_kotlin.py` from the", " * prototype's fits (docs/TERRA_STICKS.md). Do not edit by hand; refit and regenerate.",
     " * Each stroke is levelled so its full hit peaks near 1.", " */", "internal object TerraSticksTables {",
     "    /** One landing of the stick, clapper or slat: when, each note's sine and cosine level, and its noise bands (lo Hz, hi Hz, level, T60 s). */",
     "    class Hit(val time: Double, val sin: DoubleArray, val cos: DoubleArray, val bands: Array<DoubleArray>)",
     "    /** A stroke: the contact's width, the notes' bloom time (0: none), the notes (Hz, T60 s) and its hits. */",
     "    class Stroke(val widthMs: Double, val riseMs: Double, val hz: DoubleArray, val t60: DoubleArray, val hits: Array<Hit>)", ""]
for name, s in strokes.items():
    L.append(f"    val {name}: Stroke by lazy {{ Stroke({fix(f'{s['width']:.6g}')}, {fix(f'{s['rise']:.6g}')},")
    L.append(f"        {dd(s['hz'])},"); L.append(f"        {dd(s['t60'])},"); L.append("        arrayOf(")
    for h in s["hits"]:
        bands = ", ".join(dd(b) for b in h["bands"])
        L.append(f"            Hit({fix(f'{h['time']:.6g}')}, {dd(h['sin'])}, {dd(h['cos'])}, arrayOf<DoubleArray>({bands})),")
    L.append("        )) }"); L.append("")
L.append("}"); open(out_kt, "w").write("\n".join(L) + "\n")
print("strokes", {k: (len(s["hz"]), len(s["hits"]), sum(len(h["bands"]) for h in s["hits"])) for k, s in strokes.items()}, "bytes", os.path.getsize(out_kt))
