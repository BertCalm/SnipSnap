"""Recompute Ferry's exact full-system state oracle from its retained matrices.

Requires NumPy and SciPy only for fixture regeneration; JVM tests read the JSON.
The matrices were recorded from the approved Python register/speed study. They
are independent input data, not generated by the Kotlin implementation under test.
"""
import json
from pathlib import Path
import numpy as np
from scipy.linalg import expm

path = Path(__file__).resolve().parents[1] / 'synth/src/test/resources/ferry-reference.json'
fixture = json.loads(path.read_text())
for case in fixture['cases']:
    generator = 1j * np.array(case['h']) - np.diag(case['gamma'])
    initial = np.array(case['initial'], dtype=complex)
    for point in case['observations']:
        state = expm(generator * (point['frame'] / fixture['internal_rate'])) @ initial
        point['real'] = state.real.tolist()
        point['imaginary'] = state.imag.tolist()
path.write_text(json.dumps(fixture, indent=2) + '\n')
print('Recomputed exact full-system Ferry observations:', path)
