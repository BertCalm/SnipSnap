    /** Refine an individual source and its local articulation, retaining its role. */
    private fun LacquerLayer.voicing(
        source: LacquerSource = this.source, ratio: Float = this.ratio, gain: Float = this.gain,
        cutoff: Float = cutoffHz, filter: Float = filterEnvelope,
        attack: Float = envelope.attackSeconds, decay: Float = envelope.decaySeconds,
        sustain: Float = envelope.sustain, release: Float = envelope.releaseSeconds,
        delay: Float = timing.reliefSeconds, phase: Float = timing.holdPhase,
        attackRelief: Float = timing.attackRelief, decayRelief: Float = timing.decayRelief,
    ) = copy(source = source, ratio = ratio, gain = gain, cutoffHz = cutoff, filterEnvelope = filter,
        envelope = LacquerEnvelope(attack, decay, sustain, release),
        timing = timing.copy(reliefSeconds = delay, holdPhase = phase,
            attackRelief = attackRelief, decayRelief = decayRelief))

    private fun model(
        voice: LacquerVoice,
        body: (LacquerLayer) -> LacquerLayer = { it },
        edge: (LacquerLayer) -> LacquerLayer = { it },
        trail: (LacquerLayer) -> LacquerLayer = { it },
        reinforcement: (LacquerLayer) -> LacquerLayer = { it },
        processing: LacquerProcessing? = null, loop: LacquerLoopProfile? = null,
    ): LacquerProfile {
        val base = Lacquer.profileFor(voice)
        return base.copy(layers = base.layers.map { layer ->
            when (layer.role) {
                LacquerRole.BODY -> body(layer)
                LacquerRole.EDGE -> edge(layer)
                LacquerRole.TRAIL -> trail(layer)
                LacquerRole.REINFORCEMENT -> reinforcement(layer)
            }
        }, processing = processing ?: base.processing, loop = loop ?: base.loop)
    }

    private fun recipe(voice: LacquerVoice, name: String, relief: Float, sheen: Float,
        body: Float, contour: Float, glue: Float, hold: Float = 0f, profile: LacquerProfile) =
        LacquerPatch(name, voice, Lacquer.defaults(voice) + mapOf(
            "RELIEF" to relief, "SHEEN" to sheen, "BODY" to body,
            "CONTOUR" to contour, "GLUE" to glue, "HOLD" to hold), profile = profile)

