        val velocity: Float = .8f,
        val alignment: Float = 0f,
        val seconds: Float = REGULAR_SECONDS,
        val resonance: Boolean = true,
        val commonGainRouting: Boolean = false,
        val comparison: String? = null,
        val variant: String? = null,
        val macro: String? = null,
        val value: Float? = null,
    )

    private val sections = listOf(
        Triple("identities", "First light", "Start with the two voices: a broad rounded bloom and a fine moving shimmer."),
        Triple("stopped", "A frozen sculpture", "Four saved alignments per voice. REVOLVE is exactly zero; only the alignment changes within each set."),
        Triple("facets", "Broad blooms → fine reflections", "The same source, note and rotation at coarse and fine facet density. Raw playback preserves excitation level differences; native uses the engine's normal leveling."),
        Triple("mechanism", "Inside the reflection", "Controlled A/B pairs bypass the resonators or collapse spectral routing into a common gain route. These are diagnostic settings, saved alongside each patch."),
        Triple("controls", "Five controls, three positions", "Low, middle and high settings, with the other controls fixed at the selected voice defaults."),
        Triple("performance", "Notes and touch", "C2, C3 and C4, each at soft and firm velocity on BLOOM. Raw playback preserves the excitation energy difference; matched playback compares timbre."),
