            }
        }
        val allCases = cases()
        val cases = if ("--quick" in args) allCases.filter { it.section == "identities" || it.id == "bloom_frozen_0" || it.id == "bloom_routing_common" } else allCases
        require(allCases.size == 45 && allCases.map { it.id }.distinct().size == 45)
        val rows = mutableListOf<Map<String, Any?>>()
        var deterministicCheck = false
        for ((index, case) in cases.withIndex()) {
            val macros = Facet.defaults(case.voice) + case.overrides + ("HOLD" to 0f)
            val patch = FacetPatch(case.title, case.voice, macros, case.midi, case.velocity, SEED, case.alignment)
            val options = FacetOptions(seconds = case.seconds, resonance = case.resonance, commonGainRouting = case.commonGainRouting)
            val renderStarted = System.nanoTime()
            val rendered = Facet.probe(case.voice, macros, case.midi, case.velocity, SEED, case.alignment, options = options)
            val renderMillis = (System.nanoTime() - renderStarted) / 1_000_000.0
            val rawSource = Snip(rendered.raw, channels = 1, sampleRate = Dsp.RATE)
            val native = rendered.snip
            validate(rawSource, case.id + " raw")
            validate(native, case.id + " native")
            require(rawSource.frameCount == native.frameCount) { "${case.id}: raw/native durations differ" }
