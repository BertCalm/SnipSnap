    private fun writeArchives(root: File, rows: List<Map<String, Any?>>): List<Map<String, Any?>> {
        fun archive(name: String, title: String, selected: List<Map<String, Any?>>, variants: List<String>): Map<String, Any?> {
            val paths = linkedSetOf("README.txt", "report.json", "metrics.csv")
            for (row in selected) {
                for (variant in variants) paths += row.getValue(variant) as String
                paths += row.getValue("recipe") as String
                val diagnostics = row["diagnostics"] as Map<*, *>
                paths += diagnostics["settings"] as String
                paths += diagnostics["trace"] as String
            }
            val destination = File(root, name)
            ZipOutputStream(destination.outputStream().buffered()).use { zip ->
                zip.putNextEntry(ZipEntry("SELECTION.txt").apply { time = 0L })
                zip.write(("$title\n${selected.size} clips; playback variants: ${variants.joinToString()}\n" +
                    "The bundled report covers the whole audition; this archive contains only the following audio and its recipes:\n" +
                    selected.joinToString("\n") { it.getValue("id") as String } + "\n").toByteArray())
                zip.closeEntry()
                for (path in paths.sorted()) {
                    zip.putNextEntry(ZipEntry(path).apply { time = 0L })
                    File(root, path).inputStream().use { it.copyTo(zip) }
                    zip.closeEntry()
                }
            }
            require(destination.length() < 24L * 1024 * 1024) { "$name exceeds static-host file limit" }
            return mapOf("title" to title, "path" to name, "url" to name, "clipCount" to selected.size,
                "variants" to variants, "bytes" to destination.length())
        }
        val archives = mutableListOf<Map<String, Any?>>()
        val firstListen = rows.filter { it["section"] in setOf("identities", "stopped", "facets", "slow-motion") }
        archives += archive("facet-first-light.zip", "First light · matched listening selection", firstListen, listOf("matched"))
        for ((id, title) in sections.map { it.first to it.second }) {
            val sectionRows = rows.filter { it["section"] == id }
            for ((index, chunk) in sectionRows.chunked(16).withIndex()) {
                val suffix = if (sectionRows.size > 16) "-${index + 1}" else ""
                archives += archive("facet-$id$suffix.zip", "$title${if (suffix.isNotEmpty()) " · part ${index + 1}" else ""} · matched audio + recipes",
                    chunk, listOf("matched"))
            }
        }
        return archives
    }

    private fun writeJson(file: File, value: Any?) {
        file.parentFile?.mkdirs()
        file.writeText(Json.write(json(value)) + "\n")
    }

    private fun json(value: Any?): JsonValue = when (value) {
        null -> JsonValue.Null
        is JsonValue -> value
        is String -> JsonValue.Str(value)
        is Boolean -> JsonValue.Bool(value)
        is Number -> { require(value.toDouble().isFinite()) { "Non-finite JSON measurement" }; JsonValue.Num(value.toDouble()) }
        is Map<*, *> -> JsonValue.Obj(value.entries.associate { it.key.toString() to json(it.value) })
        is Iterable<*> -> JsonValue.Arr(value.map(::json))
        else -> error("Unsupported JSON value ${value::class}")
    }

    private fun sha256(file: File): String {
        val digest = MessageDigest.getInstance("SHA-256")
        file.inputStream().use { input ->
            val buffer = ByteArray(64 * 1024)
            while (true) { val n = input.read(buffer); if (n < 0) break; digest.update(buffer, 0, n) }
        }
        return digest.digest().joinToString("") { "%02x".format(it) }
    }

