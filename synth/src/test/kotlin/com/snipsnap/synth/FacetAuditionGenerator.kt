/** Finite, dry listening evidence generated by the real JVM FACET engine. */
object FacetAuditionGenerator {
    private const val REVISION = "r1-finite-prototype"
    private const val SEED = 17
    private const val REGULAR_SECONDS = 6f
    private val controls = listOf("ILLUMINATE", "ELEVATION", "CHROMA", "REVOLVE", "FACETS")
    private val voices = listOf(FacetVoice.BLOOM, FacetVoice.SHIMMER)

    private data class Case(
