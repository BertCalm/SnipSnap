    private fun validate(snip: Snip, id: String) {
        require(snip.channels == 1 && snip.sampleRate == Dsp.RATE && snip.samples.isNotEmpty()) { "$id has invalid audio format" }
        require(snip.samples.all { it.isFinite() }) { "$id contains non-finite samples" }
        require(snip.peak() > 1e-7f) { "$id is silent" }
    }

    private fun validateExport(file: File, expected: Snip): Snip {
        val actual = WavReader.read(file)
        require(actual.frameCount == expected.frameCount && actual.channels == expected.channels && actual.sampleRate == expected.sampleRate)
        require(actual.samples.indices.all { abs(actual.samples[it] - expected.samples[it]) < .0000003f }) { "${file.name}: PCM24 round-trip changed samples beyond quantization" }
        return actual
    }

    private fun amplitudeStats(snip: Snip): Map<String, Any?> {
        var sum = 0.0
        var energy = 0.0
        var largestStep = 0.0
        for (i in snip.samples.indices) {
            val value = snip.samples[i].toDouble()
            sum += value
            energy += value * value
            if (i > 0) largestStep = maxOf(largestStep, abs(value - snip.samples[i - 1]))
        }
        return linkedMapOf("peak" to snip.peak(), "rms" to sqrt(energy / snip.samples.size), "dc" to sum / snip.samples.size,
            "loudestWindowRms" to Loudness.of(snip), "maxAdjacentStep" to largestStep, "finite" to snip.samples.all { it.isFinite() })
    }

    private fun pitchMetrics(snip: Snip, midi: Int): Map<String, Any?> {
        val target = 440.0 * 2.0.pow((midi - 69) / 12.0)
        val windows = listOf(.35f, 1.1f, 2.4f).filter { it + .25f < snip.durationSeconds }.map { from ->
            val pitch = Pitch.detect(snip, from, .25f)
            mapOf("fromSeconds" to from, "hz" to pitch?.hz, "confidence" to pitch?.confidence,
                "cents" to pitch?.let { 1200.0 * ln(it.hz / target) / ln(2.0) })
        }
        val best = windows.filter { it["confidence"] != null }.maxByOrNull { (it.getValue("confidence") as Number).toDouble() }
        return linkedMapOf("requestedHz" to target, "hz" to best?.get("hz"), "cents" to best?.get("cents"),
            "confidence" to best?.get("confidence"), "selectedFromSeconds" to best?.get("fromSeconds"),
            "windows" to windows, "method" to "Shared Pitch.detect; highest confidence of three 250 ms body windows")
    }

    private fun classifierMetrics(snip: Snip): Map<String, Any?> {
        val whole = Classifier.classify(snip)
        val head = Classifier.classify(Snip(snip.samples.copyOfRange(0, minOf(snip.frameCount, (Dsp.RATE * 1.25).toInt())), 1, Dsp.RATE))
        return mapOf("whole" to whole.drumClass.name, "wholeConfidence" to whole.confidence,
            "head" to head.drumClass.name, "headConfidence" to head.confidence, "headCropSeconds" to 1.25,
            "notes" to "Whole LOOP is a duration label, not pitch evidence. Head is a diagnostic 1.25-second crop only.")
    }

    private fun clipMetric(row: Map<String, Any?>, key: String): Map<*, *> =
        (row["metrics"] as Map<*, *>)[key] as Map<*, *>

    private fun comparisonMetrics(root: File, rows: List<Map<String, Any?>>): Map<String, Any?> {
        val byId = rows.associateBy { it.getValue("id") as String }
        val routing = mutableListOf<Map<String, Any?>>()
        val density = mutableListOf<Map<String, Any?>>()
        val revision = mutableListOf<Map<String, Any?>>()
        fun compare(a: Map<String, Any?>, b: Map<String, Any?>): Map<String, Any?> {
            val first = WavReader.read(File(root, a.getValue("matched") as String))
            val second = WavReader.read(File(root, b.getValue("matched") as String))
            require(first.frameCount == second.frameCount) { "Comparison duration changed: ${a["id"]}/${b["id"]}" }
            val rmsA = (amplitudeStats(first)["rms"] as Number).toDouble().coerceAtLeast(1e-12)
            val rmsB = (amplitudeStats(second)["rms"] as Number).toDouble().coerceAtLeast(1e-12)
            var normalizedSquares = 0.0
            var normalizedProduct = 0.0
            for (i in first.samples.indices) {
                val x = first.samples[i] / rmsA
                val y = second.samples[i] / rmsB
                normalizedSquares += (x - y) * (x - y)
                normalizedProduct += x * y
            }
            val spectrumA = clipMetric(a, "spectrum")
            val spectrumB = clipMetric(b, "spectrum")
            val groupsA = spectrumA["powerFractions"] as List<*>
            val groupsB = spectrumB["powerFractions"] as List<*>
            val groupDifference = groupsA.indices.sumOf { i -> abs((groupsA[i] as Number).toDouble() - (groupsB[i] as Number).toDouble()) }
            val windowGroupsA = spectrumA["windowPowerFractions"] as List<*>
            val windowGroupsB = spectrumB["windowPowerFractions"] as List<*>
            val windowDifferences = windowGroupsA.indices.map { window ->
                val x = windowGroupsA[window] as List<*>
                val y = windowGroupsB[window] as List<*>
                x.indices.sumOf { group -> abs((x[group] as Number).toDouble() - (y[group] as Number).toDouble()) }
            }
            val rawA = clipMetric(a, "sourceRaw")
            val rawB = clipMetric(b, "sourceRaw")
            val rawRmsA = (rawA["rms"] as Number).toDouble()
            val rawRmsB = (rawB["rms"] as Number).toDouble()
            val rawMeanA = (rawA["dc"] as Number).toDouble()
            val rawMeanB = (rawB["dc"] as Number).toDouble()
            val widthA = (spectrumA["upperHarmonicWidth"] as Map<*, *>)["pooledRmsWidthHz"] as Number
            val widthB = (spectrumB["upperHarmonicWidth"] as Map<*, *>)["pooledRmsWidthHz"] as Number
            return linkedMapOf(
                "voice" to a["voice"], "first" to a["id"], "second" to b["id"],
                "midi" to a["midi"], "firstSourceModel" to a["sourceModel"], "secondSourceModel" to b["sourceModel"],
                "matchedNormalizedWaveformRmsDistance" to sqrt(normalizedSquares / first.samples.size),
                "matchedNormalizedCorrelation" to normalizedProduct / first.samples.size,
                "firstSpectralGroups" to spectrumA, "secondSpectralGroups" to spectrumB,
                "spectralGroupPowerFractionL1Difference" to groupDifference,
                "spectralGroupWindowMeanL1Difference" to windowDifferences.takeIf { it.isNotEmpty() }?.average(),
                "spectralGroupWindowMaxL1Difference" to windowDifferences.maxOrNull(),
                "firstRawRms" to rawRmsA, "secondRawRms" to rawRmsB,
                "secondToFirstRawRmsRatio" to rawRmsB / rawRmsA.coerceAtLeast(1e-12),
                "secondToFirstRawRmsDb" to 20 * log10((rawRmsB / rawRmsA.coerceAtLeast(1e-12)).coerceAtLeast(1e-12)),
                "rawRmsDifference" to rawRmsB - rawRmsA, "firstRawMean" to rawMeanA,
                "secondRawMean" to rawMeanB, "rawMeanDifference" to rawMeanB - rawMeanA,
                "spectralMetricDifferences" to listOf("effectiveHarmonicCount", "powerAbove1kFraction", "powerAbove2kFraction",
                    "powerAbove4kFraction", "fundamentalShare", "centroidHz", "bodyRmsCoefficientOfVariation",
                    "normalizedFftPowerMeanL1Change", "temporalMeanL1Change").associateWith { key ->
                    (spectrumB[key] as Number).toDouble() - (spectrumA[key] as Number).toDouble()
                },
                "upperHarmonicWidthDifferenceHz" to widthB.toDouble() - widthA.toDouble(),
            )
        }
        for (voice in voices) {
            val slug = voice.name.lowercase()
            val full = byId["${slug}_routing_spectral"]
            val common = byId["${slug}_routing_common"]
            if (full != null && common != null) routing += compare(full, common)
            val coarse = byId["${slug}_facets_coarse"]
            val fine = byId["${slug}_facets_fine"]
            if (coarse != null && fine != null) density += compare(coarse, fine)
            for (midi in listOf(48, 60)) {
                val prefix = "revision_${slug}_$midi"
                val original = byId["${prefix}_r1"]
                val clean = byId["${prefix}_r2_clean"]
                val living = byId["${prefix}_r2_living"]
                if (original != null && clean != null) revision += compare(original, clean) + ("kind" to "source-density")
                if (clean != null && living != null) revision += compare(clean, living) + ("kind" to "source-motion")
                if (original != null && living != null) revision += compare(original, living) + ("kind" to "full-revision")
            }
        }
        return mapOf("fullVersusCommonRouting" to routing, "coarseVersusFineFacets" to density, "revisionSourceComparisons" to revision)
    }

    /** Broad fixed bands around the requested root; independent of private source harmonic lists. */
    private fun spectralGroups(snip: Snip, midi: Int): Map<String, Any?> {
        val edges = listOf(.5, 1.5, 2.5, 3.5, 5.5, 8.5, 13.0, 20.0, 40.0)
        val rootHz = 440.0 * 2.0.pow((midi - 69) / 12.0)
        val size = 16384
        val hop = size / 2
        val from = (.4 * snip.sampleRate).toInt()
        val to = (minOf(snip.durationSeconds - 1.4, snip.durationSeconds * .82) * snip.sampleRate).toInt()
        val energy = DoubleArray(edges.size - 1)
        val harmonicEnergy = DoubleArray(32)
        val highEnergy = DoubleArray(3)
        val windowFractions = mutableListOf<List<Double>>()
        val frameMetrics = mutableListOf<Map<String, Any?>>()
        val frameRms = mutableListOf<Double>()
        val normalizedFftChanges = mutableListOf<Double>()
        var previousPower: DoubleArray? = null
        var allPower = 0.0
        var centroidNumerator = 0.0
        var fundamentalPower = 0.0
        var windows = 0
        for (start in from..(to - size) step hop) {
            val real = FloatArray(size) { i -> (snip.samples[start + i] * (.5 - .5 * cos(2 * PI * i / (size - 1)))).toFloat() }
            val imaginary = FloatArray(size)
            Fft.forward(real, imaginary)
            val windowEnergy = DoubleArray(energy.size)
            val power = DoubleArray(size / 2)
            var windowPower = 0.0
            var windowCentroid = 0.0
            var windowSquares = 0.0
            var windowFundamental = 0.0
            for (i in 0 until size) windowSquares += snip.samples[start + i].toDouble() * snip.samples[start + i]
            val rms = sqrt(windowSquares / size)
            frameRms += rms
            for (bin in 1 until size / 2) {
                val hz = bin.toDouble() * snip.sampleRate / size
                val ratio = hz / rootHz
                val p = real[bin].toDouble() * real[bin] + imaginary[bin].toDouble() * imaginary[bin]
                power[bin] = p
                windowPower += p
                windowCentroid += hz * p
                if (ratio >= .5 && ratio < 1.5) windowFundamental += p
                val harmonic = ratio.roundToInt()
                if (harmonic in 1..32 && abs(ratio - harmonic) < .5) harmonicEnergy[harmonic - 1] += p
                if (hz >= 1000) highEnergy[0] += p
                if (hz >= 2000) highEnergy[1] += p
                if (hz >= 4000) highEnergy[2] += p
                val group = (0 until edges.size - 1).firstOrNull { ratio >= edges[it] && ratio < edges[it + 1] }
                if (group != null) windowEnergy[group] += p
            }
            allPower += windowPower
            centroidNumerator += windowCentroid
            fundamentalPower += windowFundamental
            val safePower = windowPower.coerceAtLeast(1e-30)
            for (bin in power.indices) power[bin] /= safePower
            previousPower?.let { previous -> normalizedFftChanges += power.indices.sumOf { abs(power[it] - previous[it]) } }
            previousPower = power
            frameMetrics += mapOf("fromSeconds" to start.toDouble() / snip.sampleRate, "rms" to rms,
                "centroidHz" to windowCentroid / safePower, "fundamentalShare" to windowFundamental / safePower)
            val windowTotal = windowEnergy.sum().coerceAtLeast(1e-30)
            windowFractions += windowEnergy.map { it / windowTotal }
            for (group in energy.indices) energy[group] += windowEnergy[group]
            windows++
        }
        val total = energy.sum().coerceAtLeast(1e-30)
        val temporalChanges = windowFractions.zipWithNext { x, y -> x.indices.sumOf { abs(x[it] - y[it]) } }
        val harmonicTotal = harmonicEnergy.sum().coerceAtLeast(1e-30)
        val harmonicSquares = harmonicEnergy.sumOf { it * it }.coerceAtLeast(1e-30)
        val harmonicMaximum = (harmonicEnergy.maxOrNull() ?: 0.0).coerceAtLeast(1e-30)
        val meanRms = frameRms.takeIf { it.isNotEmpty() }?.average() ?: 0.0
        val rmsCv = sqrt(frameRms.sumOf { (it - meanRms) * (it - meanRms) } / maxOf(1, frameRms.size)) / meanRms.coerceAtLeast(1e-30)
        val safeAllPower = allPower.coerceAtLeast(1e-30)
        return linkedMapOf("rootHz" to rootHz, "rootRatioBandEdges" to edges, "fromSeconds" to from.toDouble() / snip.sampleRate,
            "toSeconds" to to.toDouble() / snip.sampleRate, "fftSize" to size, "hopFrames" to hop, "windowCount" to windows,
            "powerFractions" to energy.map { it / total }, "windowPowerFractions" to windowFractions,
            "temporalMeanL1Change" to (temporalChanges.takeIf { it.isNotEmpty() }?.average() ?: 0.0),
            "normalizedFftPowerMeanL1Change" to (normalizedFftChanges.takeIf { it.isNotEmpty() }?.average() ?: 0.0),
            "normalizedFftPowerMaxL1Change" to (normalizedFftChanges.maxOrNull() ?: 0.0),
            "effectiveHarmonicCount" to harmonicTotal * harmonicTotal / harmonicSquares,
            "harmonicCountAboveMinus40Db" to harmonicEnergy.count { it >= harmonicMaximum * 1e-4 },
            "harmonicPowerFractions" to harmonicEnergy.map { it / harmonicTotal },
            "powerAbove1kFraction" to highEnergy[0] / safeAllPower, "powerAbove2kFraction" to highEnergy[1] / safeAllPower,
            "powerAbove4kFraction" to highEnergy[2] / safeAllPower, "fundamentalShare" to fundamentalPower / safeAllPower,
            "centroidHz" to centroidNumerator / safeAllPower, "bodyRmsMean" to meanRms,
            "bodyRmsCoefficientOfVariation" to rmsCv, "bodyFrames" to frameMetrics,
            "upperHarmonicWidth" to harmonicWidth(snip, rootHz, from, to))
    }

    /** A 1.49-second Hann window resolves sub-Hz source offsets more usefully than the short frame. */
    private fun harmonicWidth(snip: Snip, rootHz: Double, from: Int, to: Int): Map<String, Any?> {
        val size = 65536
        val binHz = snip.sampleRate.toDouble() / size
        var pooledPower = 0.0
        var pooledVariancePower = 0.0
        val widths = mutableListOf<Double>()
        for (start in from..(to - size) step (size / 2)) {
            val real = FloatArray(size) { i -> (snip.samples[start + i] * (.5 - .5 * cos(2 * PI * i / (size - 1)))).toFloat() }
            val imaginary = FloatArray(size)
            Fft.forward(real, imaginary)
            var framePower = 0.0
            var frameVariancePower = 0.0
            for (harmonic in 2..32) {
                val center = rootHz * harmonic
                if (center + 8 >= snip.sampleRate / 2) break
                val lower = kotlin.math.ceil((center - 8) / binHz).toInt().coerceAtLeast(1)
                val upper = kotlin.math.floor((center + 8) / binHz).toInt().coerceAtMost(size / 2 - 1)
                var power = 0.0
                var frequencyPower = 0.0
                var frequencySquaredPower = 0.0
                for (bin in lower..upper) {
                    val p = real[bin].toDouble() * real[bin] + imaginary[bin].toDouble() * imaginary[bin]
                    val frequency = bin * binHz
                    power += p
                    frequencyPower += frequency * p
                    frequencySquaredPower += frequency * frequency * p
                }
                if (power > 1e-20) {
                    val mean = frequencyPower / power
                    val variance = (frequencySquaredPower / power - mean * mean).coerceAtLeast(0.0)
                    framePower += power
                    frameVariancePower += variance * power
                }
            }
            pooledPower += framePower
            pooledVariancePower += frameVariancePower
            widths += sqrt(frameVariancePower / framePower.coerceAtLeast(1e-30))
        }
        return mapOf("fftSize" to size, "binHz" to binHz, "windowSeconds" to size.toDouble() / snip.sampleRate,
            "localHalfWidthHz" to 8, "harmonics" to "2..32", "windowCount" to widths.size,
            "pooledRmsWidthHz" to sqrt(pooledVariancePower / pooledPower.coerceAtLeast(1e-30)), "windowRmsWidthsHz" to widths,
            "notes" to "Power-weighted local spectral standard deviation around each upper harmonic, within ±8 Hz. Finite-window width and reflection sidebands contribute; this is not a direct detune estimate.")
    }

    private fun gain(source: Snip, result: Snip): Double {
        val index = source.samples.indices.maxByOrNull { abs(source.samples[it]) } ?: return 0.0
        return if (source.samples[index] == 0f) 0.0 else result.samples[index].toDouble() / source.samples[index]
    }

    private fun waveform(samples: FloatArray): List<Float> = (0 until 120).map { bin ->
        val start = bin * samples.size / 120
        val end = ((bin + 1) * samples.size / 120).coerceAtLeast(start + 1).coerceAtMost(samples.size)
        var peak = 0f
        for (i in start until end) peak = maxOf(peak, abs(samples[i]))
        peak
    }

