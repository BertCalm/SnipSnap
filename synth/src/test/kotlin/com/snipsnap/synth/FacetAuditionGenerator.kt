/** Finite, dry listening evidence generated by the real JVM FACET engine. */
object FacetAuditionGenerator {
    private const val REVISION = "r2-living-source"
    private const val SEED = 17
    private const val REGULAR_SECONDS = 6f
    private val controls = listOf("ILLUMINATE", "ELEVATION", "CHROMA", "REVOLVE", "FACETS")
    private val voices = listOf(FacetVoice.BLOOM, FacetVoice.SHIMMER)

    private data class Case(
        val id: String,
        val section: String,
        val title: String,
        val description: String,
        val voice: FacetVoice,
        val overrides: Map<String, Float> = emptyMap(),
        val midi: Int = 48,
        val velocity: Float = .8f,
        val alignment: Float = 0f,
        val seconds: Float = REGULAR_SECONDS,
        val resonance: Boolean = true,
        val commonGainRouting: Boolean = false,
        val comparison: String? = null,
        val variant: String? = null,
        val macro: String? = null,
        val value: Float? = null,
        val modelVersion: Int = Facet.MODEL_VERSION,
        val sourceMotion: Boolean = true,
    )

    private val sections = listOf(
        Triple("revision", "A fuller source, with room to move", "Compare the original R1 source, the denser R2 source with motion off, and R2 with gentle upper-partial motion. Each trio shares controls, pitch, velocity, seed, alignment and duration. These are dry listening candidates; your listening verdict is still open."),
        Triple("identities", "First light", "Start with the two voices: a broad rounded bloom and a fine moving shimmer."),
        Triple("stopped", "A frozen sculpture", "Four saved alignments per voice. REVOLVE is exactly zero; only the alignment changes within each set."),
        Triple("facets", "Broad blooms → fine reflections", "The same source, note and rotation at coarse and fine facet density. Raw playback preserves excitation level differences; native uses the engine's normal leveling."),
        Triple("mechanism", "Inside the reflection", "Controlled A/B pairs bypass the resonators or collapse spectral routing into a common gain route. These are diagnostic settings, saved alongside each patch."),
        Triple("controls", "Five controls, three positions", "Low, middle and high settings, with the other controls fixed at the selected voice defaults."),
        Triple("performance", "Notes and touch", "C2, C3 and C4, each at soft and firm velocity on BLOOM. Raw playback preserves the excitation energy difference; matched playback compares timbre."),
        Triple("slow-motion", "Take a longer look", "Twenty seconds at the slow moving end of REVOLVE. The requested rotation is retained; these are finite recordings rather than held loops."),
    )

    @JvmStatic
    fun main(args: Array<String>) {
        require(args.count { !it.startsWith("--") } <= 1 && args.filter { it.startsWith("--") }.all { it == "--quick" || it.startsWith("--r1=") }) {
            "usage: FacetAuditionGenerator [output-directory] [--quick] [--r1=published-r1-directory]"
        }
        val root = File(args.firstOrNull { !it.startsWith("--") } ?: "../testkit/facet-audition").canonicalFile
        require(root.mkdirs() || root.isDirectory) { "Cannot create $root" }
        val started = System.nanoTime()
        val generatedAt = Instant.now().toString()
        val repository = repositoryRoot()
        val sourceFiles = listOf("synth/src/main/kotlin/com/snipsnap/synth/Facet.kt", "synth/src/main/kotlin/com/snipsnap/synth/FacetModel1.kt", "synth/src/main/kotlin/com/snipsnap/synth/FacetPatch.kt",
            "synth/src/test/kotlin/com/snipsnap/synth/FacetAuditionGenerator.kt", "synth/src/test/kotlin/com/snipsnap/synth/AuditionLevel.kt")
        val sourceSha256 = sourceFiles.filter { File(repository, it).isFile }.associateWith { sha256(File(repository, it)) }
        val runtimeSha256 = listOf(Facet::class.java, FacetModel1::class.java, FacetPatch::class.java, FacetOptions::class.java, FacetAuditionGenerator::class.java).associate { type ->
            type.name to type.getResourceAsStream("/${type.name.replace('.', '/')}.class")?.use { input ->
                MessageDigest.getInstance("SHA-256").digest(input.readBytes()).joinToString("") { "%02x".format(it) }
            }
        }
        val baselineDir = File(args.firstOrNull { it.startsWith("--r1=") }?.substringAfter('=')
            ?: File(repository.parentFile, "scratch/facet-r1-published").path).canonicalFile
        require(root != baselineDir) { "Keep the published R1 snapshot separate from new audition output" }
        val publishedR1 = archivePublishedR1(root, baselineDir)
        val allCases = cases()
        val cases = if ("--quick" in args) allCases.filter { (it.section == "revision" && it.midi == 48) || it.section == "identities" || it.id == "bloom_frozen_0" || it.id == "bloom_routing_common" } else allCases
        require(allCases.size == 57 && allCases.map { it.id }.distinct().size == 57)
        val rows = mutableListOf<Map<String, Any?>>()
        val deterministicChecks = linkedMapOf<String, Boolean>()
        for ((index, case) in cases.withIndex()) {
            val macros = Facet.defaults(case.voice) + case.overrides + ("HOLD" to 0f)
            val patch = FacetPatch(case.title, case.voice, macros, case.midi, case.velocity, SEED, case.alignment, modelVersion = case.modelVersion)
            val options = FacetOptions(seconds = case.seconds, resonance = case.resonance, commonGainRouting = case.commonGainRouting, sourceMotion = case.sourceMotion)
            val renderStarted = System.nanoTime()
            val rendered = Facet.probe(case.voice, macros, case.midi, case.velocity, SEED, case.alignment, options = options, modelVersion = case.modelVersion)
            val renderMillis = (System.nanoTime() - renderStarted) / 1_000_000.0
            val rawSource = Snip(rendered.raw, channels = 1, sampleRate = Dsp.RATE)
            val native = rendered.snip
            validate(rawSource, case.id + " raw")
            validate(native, case.id + " native")
            require(rawSource.frameCount == native.frameCount) { "${case.id}: raw/native durations differ" }
            val sourceModel = sourceModel(case)
            if (sourceModel !in deterministicChecks) {
                val replay = Facet.probe(case.voice, macros, case.midi, case.velocity, SEED, case.alignment, options = options, modelVersion = case.modelVersion)
                val identical = rendered.raw.contentEquals(replay.raw) && native.samples.contentEquals(replay.snip.samples)
                deterministicChecks[sourceModel] = identical
                check(identical) { "$sourceModel FACET replay was not sample-identical" }
            }
            // Preserve floating-point source measurements even if PCM safety attenuation is needed.
            val rawExportGain = minOf(1f, .99f / rawSource.peak().coerceAtLeast(1e-9f))
            val raw = Snip(FloatArray(rawSource.samples.size) { rawSource.samples[it] * rawExportGain }, 1, Dsp.RATE)
            val matched = AuditionLevel.level(native)
            require(native.peak() <= 1f && matched.peak() <= 1f) { "${case.id}: native/matched export would clip" }
            val rawPath = "raw/${case.id}.wav"
            val nativePath = "native/${case.id}.wav"
            val matchedPath = "matched/${case.id}.wav"
            val recipePath = "recipes/${case.id}.json"
            val settingsPath = "diagnostics/${case.id}.json"
            val tracePath = "traces/${case.id}.json"
            val sampler = SmplChunk(rootNote = case.midi)
            val rawFile = WavWriter.write(File(root, rawPath), raw, WavWriter.BitDepth.PCM_24, smpl = sampler)
            val nativeFile = WavWriter.write(File(root, nativePath), native, WavWriter.BitDepth.PCM_24, smpl = sampler)
            val matchedFile = WavWriter.write(File(root, matchedPath), matched, WavWriter.BitDepth.PCM_24, smpl = sampler)
            for (file in listOf(rawFile, nativeFile, matchedFile)) require(file.length() < 25_000_000) { "${file.name} exceeds host file limit" }
            val decodedRaw = validateExport(rawFile, raw)
            val decodedNative = validateExport(nativeFile, native)
            val decodedMatched = validateExport(matchedFile, matched)
            val hashes = mapOf("raw" to sha256(rawFile), "native" to sha256(nativeFile), "matched" to sha256(matchedFile))
            val golden = if (case.modelVersion == Facet.LEGACY_MODEL_VERSION && case.midi == 48 && case.section == "revision") {
                val expected = R1_GOLDEN.getValue(case.voice)
                require(hashes == expected) { "${case.id}: model-1 replay changed the published R1 PCM24 WAVs: $hashes" }
                mapOf("publishedId" to "${case.voice.name.lowercase()}_default", "sampleIdenticalPcm" to true, "sha256" to expected)
            } else null
            writeJson(File(root, recipePath), patch.toJsonValue())
            val diagnosticSettings = linkedMapOf(
                "schemaVersion" to 1, "engine" to "FACET", "revision" to REVISION, "modelVersion" to case.modelVersion, "sourceModel" to sourceModel,
                "patch" to patch.toJsonValue(), "recipe" to recipePath,
                "options" to linkedMapOf("seconds" to case.seconds, "resonance" to case.resonance,
                    "commonGainRouting" to case.commonGainRouting, "oversample" to options.oversample, "sourceMotion" to case.sourceMotion),
                "notes" to "Replay the saved patch fields through Facet.probe with these explicit options. Diagnostic bypasses are intentionally separate from the musical patch.",
            )
            writeJson(File(root, settingsPath), diagnosticSettings)
            writeJson(File(root, tracePath), mapOf("clip" to case.id, "samples" to rendered.trace.map { point ->
                mapOf("seconds" to point.seconds, "phase" to point.phase, "routeEnergy" to point.routeEnergy)
            }))
            val diagnostic = rendered.diagnostics
            if (macros.getValue("REVOLVE") == 0f) {
                require(diagnostic.rotorHz == 0f && diagnostic.startPhase == diagnostic.endPhase && diagnostic.routeMotion == 0f) {
                    "${case.id}: stopped alignment moved"
                }
            }
            val diagnostics = linkedMapOf<String, Any?>(
                "settings" to settingsPath, "trace" to tracePath,
                "preparationMillis" to diagnostic.preparationMillis, "synthesisMillis" to diagnostic.synthesisMillis,
                "renderMillis" to renderMillis, "msPerAudioSecond" to renderMillis / native.durationSeconds,
                "rawPeak" to diagnostic.rawPeak, "rawRms" to diagnostic.rawRms, "rawDc" to diagnostic.rawDc,
                "statePeak" to diagnostic.statePeak, "rotorHz" to diagnostic.rotorHz,
                "startPhase" to diagnostic.startPhase, "endPhase" to diagnostic.endPhase,
                "effectiveFacets" to diagnostic.effectiveFacets, "routeDiversity" to diagnostic.routeDiversity,
                "routeMotion" to diagnostic.routeMotion, "oversample" to diagnostic.oversample,
                "resonance" to case.resonance, "commonGainRouting" to case.commonGainRouting,
                "modelVersion" to case.modelVersion, "sourceMotion" to case.sourceMotion,
            )
            val metrics = linkedMapOf(
                "sourceRaw" to amplitudeStats(rawSource), "raw" to amplitudeStats(decodedRaw),
                "native" to amplitudeStats(decodedNative), "matched" to amplitudeStats(decodedMatched),
                "rawExportGain" to rawExportGain, "matchingGain" to gain(native, matched),
                "pitch" to pitchMetrics(decodedNative, case.midi), "classifier" to classifierMetrics(decodedNative),
                "spectrum" to spectralGroups(decodedMatched, case.midi),
            )
            val wholeClass = (metrics["classifier"] as Map<*, *>)["whole"].toString()
            require(wholeClass !in setOf("KICK", "SNARE", "CLAP", "HAT_CLOSED", "HAT_OPEN", "TOM")) {
                "${case.id}: complete pitched recording classified as $wholeClass"
            }
            val row = linkedMapOf<String, Any?>(
                "id" to case.id, "title" to case.title, "label" to case.title, "description" to case.description,
                "section" to case.section, "voice" to case.voice.name, "midi" to case.midi, "noteName" to noteName(case.midi),
                "velocity" to case.velocity, "seconds" to native.durationSeconds, "frames" to native.frameCount,
                "macros" to macros, "alignment" to case.alignment, "seed" to SEED,
                "modelVersion" to case.modelVersion, "sourceMotion" to case.sourceMotion, "sourceModel" to sourceModel,
                "sourceModelLabel" to sourceModelLabel(case), "currentDefault" to (case.modelVersion == Facet.MODEL_VERSION && case.sourceMotion),
                "raw" to rawPath, "native" to nativePath, "matched" to matchedPath,
                "recipe" to recipePath, "recipeUrl" to recipePath, "diagnostics" to diagnostics, "metrics" to metrics,
                "comparison" to if (case.section == "revision") mapOf("group" to case.comparison, "variant" to case.variant,
                    "order" to when (case.variant) { "r1" -> 0; "r2_clean" -> 1; else -> 2 }) else case.comparison,
                "variant" to case.variant, "macro" to case.macro, "value" to case.value, "goldenReplay" to golden,
                "waveform" to waveform(decodedMatched.samples),
                "sha256" to hashes,
            )
            rows += row
            println("FACET ${index + 1}/${cases.size}: ${case.id}, ${native.durationSeconds}s, ${renderMillis.roundToInt()} ms, raw peak ${rawSource.peak()}")
        }
        require(sourceSha256.all { (path, hash) -> File(repository, path).isFile && sha256(File(repository, path)) == hash }) {
            "FACET renderer sources changed during generation; compile the final sources and regenerate before publication"
        }
        val provenance = mapOf("repository" to "https://github.com/BertCalm/SnipSnap", "revision" to git(repository, "rev-parse", "HEAD"),
            "workingTreeDirty" to (git(repository, "status", "--porcelain")?.isNotBlank() ?: true),
            "sourceSha256" to sourceSha256, "runtimeClassSha256" to runtimeSha256)
        val summary = linkedMapOf(
            "clipCount" to rows.size, "wavCount" to rows.size * 3, "voices" to 2,
            "totalAudioSeconds" to rows.sumOf { (it.getValue("seconds") as Number).toDouble() },
            "allFinite" to true, "pcmExportsVerified" to true, "defaultReplaySampleIdentical" to deterministicChecks.values.all { it },
            "deterministicBySourceModel" to deterministicChecks, "publishedR1GoldenReplays" to rows.count { it["goldenReplay"] != null },
            "models" to rows.groupingBy { it.getValue("sourceModel") as String }.eachCount(),
            "maxRawPeak" to rows.maxOf { row ->
                val metrics = row["metrics"] as Map<*, *>
                val source = metrics["sourceRaw"] as Map<*, *>
                (source["peak"] as Number).toDouble()
            },
            "maxNativePeak" to rows.maxOf { row ->
                val metrics = row["metrics"] as Map<*, *>
                val native = metrics["native"] as Map<*, *>
                (native["peak"] as Number).toDouble()
            },
            "renderMillis" to rows.sumOf { ((it["diagnostics"] as Map<*, *>)["renderMillis"] as Number).toDouble() },
            "wholeClassifierCounts" to rows.groupingBy { clipMetric(it, "classifier")["whole"].toString() }.eachCount(),
            "wholePercussionGuardPassed" to true,
            "headClassifierCounts" to rows.groupingBy { ((it["metrics"] as Map<*, *>)["classifier"] as Map<*, *>)["head"].toString() }.eachCount(),
            "classifierNotes" to "Whole-file LOOP is assigned by duration and does not prove pitch. Head counts classify only the diagnostic first 1.25-second crop; they are not the complete recording's classification.",
            "pitchMaxAbsCents" to rows.mapNotNull { (clipMetric(it, "pitch")["cents"] as? Number)?.toDouble()?.let(::abs) }.maxOrNull(),
            "pitchMinConfidence" to rows.mapNotNull { (clipMetric(it, "pitch")["confidence"] as? Number)?.toDouble() }.minOrNull(),
            "pitchUnresolvedClips" to rows.filter { clipMetric(it, "pitch")["hz"] == null }.map { it["id"] },
            "pitchReviewClips" to rows.filter {
                val pitch = (it["metrics"] as Map<*, *>)["pitch"] as Map<*, *>
                val cents = pitch["cents"] as? Number
                val confidence = pitch["confidence"] as? Number
                cents == null || abs(cents.toDouble()) > 35 || confidence == null || confidence.toDouble() < .5
            }.map { it["id"] },
            "stoppedAlignmentsExact" to rows.filter { it["section"] == "stopped" }.all {
                val diag = it["diagnostics"] as Map<*, *>
                (diag["rotorHz"] as Number).toFloat() == 0f && diag["startPhase"] == diag["endPhase"] && (diag["routeMotion"] as Number).toFloat() == 0f
            },
            "finiteOnly" to true, "heldLoopsImplemented" to false,
        )
        val comparisons = comparisonMetrics(root, rows)
        val report = linkedMapOf("schemaVersion" to 1, "engine" to "FACET", "revision" to REVISION,
            "generatedAt" to generatedAt, "metricNotes" to METRIC_NOTES, "provenance" to provenance, "publishedR1" to publishedR1,
            "summary" to summary, "comparisons" to comparisons, "comparisonMetricNotes" to COMPARISON_METRIC_NOTES, "clips" to rows)
        writeJson(File(root, "report.json"), report)
        writeCsv(File(root, "metrics.csv"), rows)
        writeJson(File(root, "recipes.json"), mapOf("schemaVersion" to 1, "engine" to "FACET", "revision" to REVISION,
            "clips" to rows.map { mapOf("id" to it["id"], "recipe" to it["recipe"], "diagnostics" to (it["diagnostics"] as Map<*, *>)["settings"]) }))
        val manifest = linkedMapOf<String, Any?>(
            "schemaVersion" to 1, "title" to "FACET · A living source", "revision" to REVISION, "generatedAt" to generatedAt,
            "description" to "A denser harmonic source and restrained upper-partial motion for FACET. Compare original R1, dense R2 with motion off, and the full R2 source through the same dry reflection mechanism.",
            "status" to "R2 finite listening candidate · acceptance pending · HOLD loops and remaining voices deferred",
            "engine" to "FACET", "sampleRate" to Dsp.RATE, "channels" to 1, "bitDepth" to 24,
            "metricNotes" to METRIC_NOTES, "provenance" to provenance, "summary" to summary, "publishedR1" to publishedR1,
            "comparisons" to comparisons, "comparisonMetricNotes" to COMPARISON_METRIC_NOTES,
            "sections" to sections.mapNotNull { (id, title, description) ->
                rows.filter { it["section"] == id }.takeIf { it.isNotEmpty() }?.let {
                    linkedMapOf("id" to id, "title" to title, "description" to description, "clips" to it)
                }
            },
            "downloads" to mapOf("zip" to "facet-first-light.zip", "report" to "report.json", "metrics" to "metrics.csv", "recipes" to "recipes.json"),
        )
        File(root, "README.txt").writeText("""
