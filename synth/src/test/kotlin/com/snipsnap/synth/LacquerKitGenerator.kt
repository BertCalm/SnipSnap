package com.snipsnap.synth

import com.snipsnap.json.Json
import com.snipsnap.json.JsonValue
import com.snipsnap.kit.ArrangedPad
import com.snipsnap.kit.KitAssembler
import com.snipsnap.kit.KitStore
import com.snipsnap.kit.Mpc3Exporter
import java.io.File
import java.security.MessageDigest
import java.util.Locale
import java.util.zip.ZipEntry
import java.util.zip.ZipOutputStream

/**
 * Export the original sixteen dry starter pads plus all 36 saved recipes in three
 * twelve-pad programs. Every program has native MPC 3 and MPC 2 twins. HOLD pads
 * contain settled loop material and play once in these drum programs.
 */
object LacquerKitGenerator {
    @JvmStatic
    fun main(args: Array<String>) {
        val root = File(args.firstOrNull() ?: "../testkit").absoluteFile
        val work = File(root, ".lacquer-work")
        val destination = File(root, "SnipSnap Lacquer Kit")
        check(root.isDirectory || root.mkdirs())
        work.deleteRecursively()
        try {
            val starter = SynthKits.lacquer()
            check(starter.size == 16) { "the original Lacquer starter must remain sixteen pads" }
            val kit = KitAssembler.assembleArranged("SnipSnap Lacquer Kit", starter, work)
            val result = Mpc3Exporter.exportTrack(kit, work, destination, overwrite = true, mpc2Twin = true)
            val archiveFile = File(root, "SnipSnap-Lacquer-Kit.zip")
            archive(destination, archiveFile)
            println("Wrote ${result.program.absolutePath}, ${result.samples.size} samples, MPC 2 twin and ${archiveFile.absolutePath}")
            exportBank(root, work)
        } finally {
            work.deleteRecursively()
        }
    }

    private fun exportBank(root: File, work: File) {
        val presets = LacquerPresets.all()
        check(presets.size == 36 && presets.map { it.name }.distinct().size == 36)
        check(LacquerVoice.entries.all { voice -> presets.count { it.voice == voice } == 6 })
        val references = LacquerPresets.references().map { it.name }.toSet()
        val destination = File(root, "SnipSnap Lacquer Bank")
        // This directory is exclusively generated by this utility; remove obsolete program assets.
        destination.deleteRecursively()
        check(destination.mkdirs())
        val groups = listOf(
            "Keys Glass" to listOf(LacquerVoice.KEY, LacquerVoice.GLASS),
            "Brass Bass" to listOf(LacquerVoice.BRASS, LacquerVoice.BASS),
            "Pluck Silk" to listOf(LacquerVoice.PLUCK, LacquerVoice.SILK),
        )
        val programs = groups.map { (title, voices) ->
            val name = "SnipSnap Lacquer $title"
            val selected = voices.flatMap { voice -> presets.filter { it.voice == voice } }
            check(selected.size == 12 && selected.size <= 32)
            val arranged = selected.map { patch ->
                val recipe = PadRecipe(patch)
                ArrangedPad(recipe.render(), Lacquer.drumClassFor(patch.voice, patch.macros),
                    recipe.toJsonValue(), oneShot = true, displayName = patch.name)
            }
            val staging = File(work, title.replace(' ', '-'))
            val kit = KitAssembler.assembleArranged(name, arranged, staging)
            check(kit.pads.size == 12)
            kit.pads.zip(selected).forEach { (pad, patch) ->
                val saved = PadRecipe.fromJsonValue(requireNotNull(pad.recipe))
                check(saved.fx == null && saved.patch?.toJsonValue() == patch.toJsonValue()) {
                    "$name pad ${pad.slot} did not preserve the complete dry recipe"
                }
            }
            val programRoot = File(destination, name)
            val result = Mpc3Exporter.exportTrack(kit, staging, programRoot, overwrite = true, mpc2Twin = true)
            check(result.samples.size == 12)
            val data = result.samples.first().parentFile
            // Keep standard editable recipes beside their exact exported sample filenames.
            check(kit.pads.all { pad -> result.samples.any { it.name == pad.sampleFile } })
            KitStore.save(kit, data)
            val savedKit = KitStore.load(data)
            check(savedKit.pads.map { it.recipe } == kit.pads.map { it.recipe })
            JsonValue.Obj(linkedMapOf(
                "name" to JsonValue.Str(name),
                "voices" to JsonValue.Arr(voices.map { JsonValue.Str(it.name) }),
                "presetCount" to JsonValue.Num(selected.size.toDouble()),
                "presetNames" to JsonValue.Arr(selected.map { JsonValue.Str(it.name) }),
                "programFile" to JsonValue.Str(result.program.relativeTo(destination).invariantSeparatorsPath),
                "recipeFile" to JsonValue.Str(File(data, "kit.json").relativeTo(destination).invariantSeparatorsPath),
                "samples" to JsonValue.Arr(kit.pads.zip(selected).map { (pad, patch) ->
                    val sample = File(data, pad.sampleFile)
                    JsonValue.Obj(linkedMapOf(
                        "pad" to JsonValue.Num(pad.slot.toDouble()), "name" to JsonValue.Str(patch.name),
                        "voice" to JsonValue.Str(patch.voice.name), "reference" to JsonValue.Bool(patch.name in references),
                        "file" to JsonValue.Str(sample.relativeTo(destination).invariantSeparatorsPath),
                        "sha256" to JsonValue.Str(sha256(sample)), "oneShot" to JsonValue.Bool(true),
                        "patch" to patch.toJsonValue(),
                    ))
                }),
            ))
        }
        val manifest = JsonValue.Obj(linkedMapOf(
            "engine" to JsonValue.Str("LACQUER"), "presetCount" to JsonValue.Num(36.0),
            "referenceCount" to JsonValue.Num(references.size.toDouble()), "programCount" to JsonValue.Num(3.0),
            "playback" to JsonValue.Str("MPC drum programs: each sample plays once, including held material. These are not sustained keygroup instruments."),
            "programs" to JsonValue.Arr(programs),
        ))
        File(destination, "bank.json").writeText(Json.write(manifest) + "\n")
        val archiveFile = File(root, "SnipSnap-Lacquer-Bank.zip")
        archive(destination, archiveFile)
        println("Wrote three twelve-pad dry programs, all 36 complete recipes and ${archiveFile.absolutePath}")
    }

    private fun archive(directory: File, archive: File) {
        ZipOutputStream(archive.outputStream().buffered()).use { zip ->
            directory.walkTopDown().filter { it.isFile }.sortedBy { it.relativeTo(directory).invariantSeparatorsPath }
                .forEach { file ->
                    val path = directory.name + "/" + file.relativeTo(directory).invariantSeparatorsPath
                    zip.putNextEntry(ZipEntry(path).also { it.time = 0L })
                    file.inputStream().use { it.copyTo(zip) }
                    zip.closeEntry()
                }
        }
    }

    private fun sha256(file: File) = MessageDigest.getInstance("SHA-256").digest(file.readBytes())
        .joinToString("") { "%02x".format(Locale.ROOT, it.toInt() and 255) }
}
