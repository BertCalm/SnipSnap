            }
        }
    }

    @Test
    fun `audio progresses in opposite directions and MOTION changes travel time without changing destinations`() {
        for (voice in OrigamiVoice.entries) {
            val slow = patch(voice, OrigamiGesture.BLOOM, 1f)
            val fast = patch(voice, OrigamiGesture.BLOOM, 0f)
            val source = slow.copy(gesture = OrigamiGesture.STEADY,
                macros = slow.macros + mapOf("FOLD" to 0f, "MOTION" to 0f))
            val folded = source.copy(macros = source.macros + ("FOLD" to slow.macros.getValue("FOLD")))
            val dry = raw(source)
            val wet = raw(folded)
            val start = OrigamiGestures.startSeconds(voice)
            val duration = OrigamiGestures.durationSeconds(voice, 1f)
            val times = listOf(start + duration * .18, start + duration * .50, start + duration * .82)
            val blooming = times.map { projection(raw(slow), dry, wet, it) }
            val unfolding = times.map { projection(raw(slow.copy(gesture = OrigamiGesture.UNFOLD)), dry, wet, it) }
            println("ORIGAMI $voice gesture audio projection at $times: BLOOM$blooming UNFOLD$unfolding")
            assertTrue(blooming.zipWithNext().all { (a, b) -> b > a + .15 }, "$voice BLOOM never unfolds a distinct source into its fold")
            assertTrue(unfolding.zipWithNext().all { (a, b) -> b < a - .15 }, "$voice UNFOLD never returns to the source")
            val plateau = OrigamiGestures.endSeconds(slow) + .1
            assertTrue(abs(projection(raw(slow), dry, wet, plateau) - 1.0) < .015, "$voice BLOOM did not settle at maximum FOLD")
            assertTrue(abs(projection(raw(slow.copy(gesture = OrigamiGesture.UNFOLD)), dry, wet, plateau)) < .015,
                "$voice UNFOLD did not settle at source")
            val middle = start + duration * .4
            assertTrue(projection(raw(fast), dry, wet, middle) > projection(raw(slow), dry, wet, middle) + .3,
                "$voice MOTION did not make the new gesture slower toward its top")
            assertTrue(OrigamiGestures.durationSeconds(voice, 0f) < OrigamiGestures.durationSeconds(voice, .5f) &&
                OrigamiGestures.durationSeconds(voice, .5f) < duration)
            assertTrue(relativeError(wet, raw(OrigamiGestures.settledPatch(slow))) < 1e-7)
        }
    }

    @Test
    fun `a gesture changes folded spectral energy rather than sweeping the root or destination frequency`() {
        for (voice in listOf(OrigamiVoice.FAN, OrigamiVoice.STILL)) {
            val bloom = patch(voice, OrigamiGesture.BLOOM, 1f)
            val samples = raw(bloom)
            val root = 440.0 * 2.0.pow((60 - 69) / 12.0)
            val target = root * if (voice == OrigamiVoice.FAN) 1.5 else 2.5
            val start = OrigamiGestures.startSeconds(voice)
            val duration = OrigamiGestures.durationSeconds(voice, 1f)
            val early = spectrum(samples, start + duration * .2, .16)
            val late = spectrum(samples, OrigamiGestures.endSeconds(bloom) + .12, .16)
            val earlyFold = fraction(early, target * .96, target * 1.04)
            val lateFold = fraction(late, target * .96, target * 1.04)
            assertTrue(lateFold > earlyFold * 4 && lateFold > .015,
                "$voice BLOOM has no level-normalized arrival at its folded body ($earlyFold -> $lateFold)")
            val mid = spectrum(samples, start + duration * .7, .16)
            val midPeak = peak(mid, target * .96, target * 1.04)
            val latePeak = peak(late, target * .96, target * 1.04)
            assertTrue(abs(midPeak - latePeak) < 1.5,
                "$voice gesture glided its destination ($midPeak -> $latePeak Hz)")
            for (center in listOf(start + duration * .2, start + duration * .7, OrigamiGestures.endSeconds(bloom) + .12)) {
                val spectrum = spectrum(samples, center, .3)
                assertTrue(abs(FineTuning.cents(peak(spectrum, root * .98, root * 1.02), root)) < 1,
                    "$voice gesture retuned the anchor near ${center}s")
            }
        }
    }

    @Test
    fun `fold remains maximum depth and manual geometry still changes the destination`() {
        for (voice in OrigamiVoice.entries) {
            val bloom = patch(voice, OrigamiGesture.BLOOM)
            val reference = raw(bloom)
            val first = ((OrigamiGestures.endSeconds(bloom) + .1) * rate).roundToInt()
            val until = minOf(reference.size, first + rate / 3)
            for ((control, value) in mapOf("CREASE" to .2f, "TURN" to .7f, "WARP" to .7f)) {
                val edited = bloom.copy(macros = bloom.macros + (control to value))
                assertTrue(matchedDifference(reference, raw(edited), first, until) > .04,
                    "$voice $control stopped changing the folded plateau in BLOOM mode")
            }
            if (voice == OrigamiVoice.CRANE) continue
            val root = 440.0 * 2.0.pow((60 - 69) / 12.0)
            val target = root * if (voice == OrigamiVoice.FAN) 1.5 else 2.5
            val center = OrigamiGestures.endSeconds(bloom) + .2
            val shallow = raw(bloom.copy(macros = bloom.macros + ("FOLD" to .25f)))
            val deep = raw(bloom.copy(macros = bloom.macros + ("FOLD" to 1f)))
            val shallowPower = fraction(spectrum(shallow, center, .3), target * .96, target * 1.04)
            val deepPower = fraction(spectrum(deep, center, .3), target * .96, target * 1.04)
            assertTrue(deepPower > shallowPower * 4,
                "$voice FOLD no longer sets the destination depth ($shallowPower -> $deepPower)")
        }
    }

    @Test
    fun `conditioning uses one gain and gestures remain bounded deterministic and cancellable`() {
        for (voice in OrigamiVoice.entries) for (gesture in gestures) {
            val saved = patch(voice, gesture)
            val unlevelled = raw(saved)
            val before = unlevelled.copyOf()
            val rendered = saved.render()
            val gain = unlevelled.indices.sumOf { unlevelled[it].toDouble() * rendered.samples[it] } /
                unlevelled.sumOf { it.toDouble() * it }.coerceAtLeast(1e-30)
            val scaled = FloatArray(unlevelled.size) { (unlevelled[it] * gain).toFloat() }
            assertTrue(relativeError(scaled, rendered.samples) < 2e-7,
                "$voice $gesture normalization changed the evolving blend within the note")
            assertContentEquals(before, unlevelled, "conditioning mutated a shared gesture reference")
            assertContentEquals(unlevelled, OrigamiGestureRenderer.renderRaw(saved), "$voice $gesture rerenders diverged")
            assertTrue(rendered.samples.all { it.isFinite() && abs(it) <= .99001f })
            assertTrue(OrigamiGestureRenderer.renderRaw(saved.copy(velocity = 0f)).all { it == 0f })
            val hot = saved.copy(midi = 72, velocity = 1f, seed = Long.MAX_VALUE - 13L,
                macros = saved.macros + mapOf("CREASE" to 1f, "FOLD" to 1f, "TURN" to 1f, "WARP" to 1f, "MOTION" to 1f))
            val extreme = OrigamiGestureRenderer.renderRaw(hot)
            assertTrue(extreme.all { it.isFinite() && abs(it) < 1f }, "$voice $gesture raw levels exploded")
            val s = spectrum(extreme, .7, .5)
            assertTrue(fraction(s, 19500.0, rate / 2.0) < 1e-5, "$voice $gesture has appreciable Nyquist-edge power")
            assertFailsWith<CancellationException> { OrigamiGestureRenderer.render(saved) { true } }
        }
        val saved = patch(OrigamiVoice.FAN, OrigamiGesture.BLOOM).copy(seed = -9007199254740993L)
        val changedTune = saved.copy(macros = saved.macros + ("TUNE" to 0f))
        assertContentEquals(raw(saved), raw(changedTune), "explicit MIDI lost priority in gesture mode")
        assertContentEquals(OrigamiGestureRenderer.renderRaw(saved, midi = 48), raw(saved.copy(midi = 48)),
            "a keyboard zone did not override the patch's saved note")
        var checks = 0
        assertFailsWith<CancellationException> { OrigamiGestureRenderer.renderRaw(saved) { ++checks >= 3 } }
        assertEquals(3, checks, "a cancelled gesture continued rendering")
    }

    @Test
    fun `held gestures finish before the loop and never start again at its wrap`() {
        for (voice in listOf(OrigamiVoice.FAN, OrigamiVoice.STILL)) for (gesture in gestures) {
            val saved = patch(voice, gesture, 1f)
            val held = OrigamiKeys.probe(saved, 60)
            val prefix = held.finitePrefixFrames
            assertTrue(held.loopStartFrame.toDouble() / rate >= OrigamiGestures.endSeconds(saved) + .04,
                "$voice $gesture enters its loop before the one-time gesture has settled")
            assertContentEquals(saved.render().samples.copyOfRange(0, prefix),
                held.note.snip.samples.copyOfRange(0, prefix), "$voice held attack ignored its saved gesture")
            val loop = held.note.snip.samples.copyOfRange(held.loopStartFrame, held.note.snip.frameCount)
            assertTrue(relativeError(loop, held.nextCycle) < 1e-7)
            assertTrue(relativeError(held.rawLoop, held.rawNextCycle) < 1e-7)
            assertTrue(held.maxPhaseClosureCycles < 1e-7, "$voice $gesture oscillator phase integral does not close")
            assertTrue(abs(held.rootCents) < .1)
            assertTrue(rms(loop) > .015)
            val step = abs(loop.first() - loop.last())
            val ordinaryStep = (1 until loop.size).maxOf { abs(loop[it] - loop[it - 1]) }
            val bend = abs((loop[1] - loop[0]) - (loop[0] - loop.last()))
            val ordinaryBend = (2 until loop.size).maxOf { abs(loop[it] - 2 * loop[it - 1] + loop[it - 2]) }
            assertTrue(step <= ordinaryStep * 1.03 + 1e-7 && bend <= ordinaryBend * 1.03 + 1e-7,
                "$voice $gesture creates a click or a slope jump when held")
            val root = held.effectiveHz
            val target = root * if (voice == OrigamiVoice.FAN) 1.5 else 2.5
            val powers = listOf(.125, .375, .625, .875).map { position ->
                fraction(spectrum(loop, position * loop.size / rate, .35), target * .96, target * 1.04)
            }
            if (gesture == OrigamiGesture.UNFOLD) {
                assertTrue(powers.all { it < 1e-4 }, "$voice UNFOLD folded again inside its source plateau: $powers")
            } else {
                assertTrue(powers.min() > .015 && powers.max() < powers.min() * 1.2,
                    "$voice BLOOM replayed its arrival or kept moving its crease inside the loop: $powers")
            }
        }
    }

