    private fun raw(patch: OrigamiPatch, diagnostic: OrigamiDiagnostic = OrigamiDiagnostic.COMBINED): FloatArray =
        audio.computeIfAbsent(patch to diagnostic) { OrigamiGestureRenderer.renderRaw(patch, diagnostic = diagnostic) }

