    private val rate = Dsp.RATE
    private val gestures = listOf(OrigamiGesture.BLOOM, OrigamiGesture.UNFOLD)

    private fun patch(voice: OrigamiVoice, gesture: OrigamiGesture = OrigamiGesture.STEADY,
                      motion: Float = .75f): OrigamiPatch = OrigamiPatch(
        "Gesture paper", voice,
        linkedMapOf("TUNE" to .5f, "CREASE" to .5f, "FOLD" to .75f,
