    @Test
    fun `cached oscillator fields share geometry but never leak a prior envelope or mutable output`() {
        OrigamiGestureRenderer.clearCache()
        val saved = patch(OrigamiVoice.FAN, OrigamiGesture.BLOOM)
        val first = OrigamiGestureRenderer.renderRaw(saved)
        val expected = first.copyOf()
        val bytes = OrigamiGestureRenderer.cacheBytes()
        assertEquals(1, OrigamiGestureRenderer.cacheEntryCount())
        assertTrue(bytes > 0)
        val changed = saved.copy(gesture = OrigamiGesture.UNFOLD, velocity = .4f,
            macros = saved.macros + mapOf("FOLD" to .4f, "MOTION" to 1f))
        OrigamiGestureRenderer.renderRaw(changed)
        assertEquals(1, OrigamiGestureRenderer.cacheEntryCount(), "FOLD, MOTION, gesture and velocity rebuilt fixed geometry")
        assertEquals(bytes, OrigamiGestureRenderer.cacheBytes())
        first[first.size / 3] = 10f
        assertContentEquals(expected, OrigamiGestureRenderer.renderRaw(saved),
            "a caller's previous output or changed envelope mutated the shared oscillator field")
        OrigamiGestureRenderer.renderRaw(saved.copy(macros = saved.macros + ("TURN" to .7f)))
        assertEquals(2, OrigamiGestureRenderer.cacheEntryCount())
        OrigamiGestureRenderer.renderRaw(saved.copy(seed = saved.seed + 1))
        assertEquals(2, OrigamiGestureRenderer.cacheEntryCount(), "the bounded cache retained a third bank")
        assertTrue(OrigamiGestureRenderer.cacheBytes() <= bytes * 2)
        OrigamiGestureRenderer.clearCache()
        var callbacks = 0
        assertFailsWith<CancellationException> {
            OrigamiGestureRenderer.renderRaw(saved) { ++callbacks >= 3 }
        }
        assertEquals(0, OrigamiGestureRenderer.cacheEntryCount(), "a cancelled build published an incomplete oscillator bank")
        assertContentEquals(expected, OrigamiGestureRenderer.renderRaw(saved))
    }

