    @Test
    fun `gesture recipes require their independent version and reject unsupported legacy modes`() {
        for (voice in OrigamiVoice.entries) for (gesture in gestures) {
            val saved = patch(voice, gesture).copy(seed = Long.MIN_VALUE + 17L)
            assertEquals(saved, Patches.fromJsonText(saved.toJsonText()))
            val fields = saved.toJsonValue().entries
            assertEquals(mapOf("name" to JsonValue.Str(gesture.name), "model" to JsonValue.Num(1.0)),
                fields.getValue("gesture").obj())
            for (legacy in 1..3) {
                assertFailsWith<IllegalArgumentException> { saved.copy(model = legacy) }
                assertFailsWith<IllegalArgumentException> {
                    Patches.fromJsonValue(JsonValue.Obj(fields + ("model" to JsonValue.Num(legacy.toDouble()))))
                }
            }
            val malformed = listOf(
                JsonValue.Str(gesture.name), JsonValue.Obj(emptyMap()),
                JsonValue.Obj(mapOf("name" to JsonValue.Str(gesture.name))),
                JsonValue.Obj(mapOf("name" to JsonValue.Str("FUTURE"), "model" to JsonValue.Num(1.0))),
                JsonValue.Obj(mapOf("name" to JsonValue.Str(gesture.name), "model" to JsonValue.Num(99.0))),
                JsonValue.Obj(mapOf("name" to JsonValue.Str(gesture.name), "model" to JsonValue.Num(1.5))),
            )
            for (value in malformed) assertFailsWith<JsonException> {
                OrigamiPatch.fromJsonValue(JsonValue.Obj(fields + ("gesture" to value)))
            }
        }
    }

    @Test
    fun `complementary gestures reconstruct source plus folded audio and leave the root untouched`() {
        for (voice in OrigamiVoice.entries) {
            val bloom = patch(voice, OrigamiGesture.BLOOM)
            val unfold = bloom.copy(gesture = OrigamiGesture.UNFOLD)
            val static = bloom.copy(gesture = OrigamiGesture.STEADY, macros = bloom.macros + ("MOTION" to 0f))
            val source = static.copy(macros = static.macros + ("FOLD" to 0f))
            val a = raw(bloom)
            val b = raw(unfold)
            val dry = raw(source)
            val folded = raw(static)
            val sum = FloatArray(a.size) { a[it] + b[it] }
            val reference = FloatArray(a.size) { dry[it] + folded[it] }
            assertTrue(relativeError(reference, sum) < 2e-6,
                "$voice BLOOM+UNFOLD did not conserve the source/reflected amplitude split")
            val anchor = raw(static, OrigamiDiagnostic.ROOT_ONLY)
            assertContentEquals(anchor, raw(bloom, OrigamiDiagnostic.ROOT_ONLY), "$voice BLOOM moved or enveloped the root")
            assertContentEquals(anchor, raw(unfold, OrigamiDiagnostic.ROOT_ONLY), "$voice UNFOLD moved or enveloped the root")
            assertEquals(a.size, Origami.durationSeconds(voice).times(rate).roundToInt())
        }
    }

    @Test
    fun `zero fold is exactly the source under either gesture and extreme geometry and duration`() {
        for (voice in OrigamiVoice.entries) {
