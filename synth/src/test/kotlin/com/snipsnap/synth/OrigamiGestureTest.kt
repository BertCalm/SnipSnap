    private fun projection(samples: FloatArray, source: FloatArray, folded: FloatArray, seconds: Double): Double {
        val half = (rate * .012).toInt()
        val center = (rate * seconds).roundToInt()
        val from = (center - half).coerceAtLeast(0)
        val until = (center + half).coerceAtMost(samples.size)
        var signal = 0.0
        var difference = 0.0
        for (i in from until until) {
            val delta = folded[i] - source[i].toDouble()
            signal += (samples[i] - source[i]) * delta
            difference += delta * delta
        }
        assertTrue(difference > 1e-9, "fixture has no source/fold contrast at $seconds s")
        return signal / difference
    }

    private data class Spectrum(val power: DoubleArray, val binHz: Double)

    private fun spectrum(samples: FloatArray, centerSeconds: Double, seconds: Double): Spectrum {
        val count = (seconds * rate).roundToInt()
        val first = ((centerSeconds * rate).roundToInt() - count / 2).coerceIn(0, samples.size - count)
        val real = FloatArray(65536)
        val imaginary = FloatArray(real.size)
        for (i in 0 until count) real[i] = (samples[first + i] * (.5 - .5 * cos(2 * PI * i / (count - 1)))).toFloat()
        Fft.forward(real, imaginary)
        return Spectrum(DoubleArray(real.size / 2) { real[it].toDouble() * real[it] + imaginary[it].toDouble() * imaginary[it] },
            rate.toDouble() / real.size)
    }

    private fun fraction(s: Spectrum, low: Double, high: Double): Double =
        s.power.indices.filter { it * s.binHz in low..high }.sumOf { s.power[it] } / s.power.drop(1).sum().coerceAtLeast(1e-30)

    private fun peak(s: Spectrum, low: Double, high: Double): Double {
        val best = s.power.indices.filter { it * s.binHz in low..high }.maxBy { s.power[it] }
        val a = sqrt(s.power[best - 1]); val b = sqrt(s.power[best]); val c = sqrt(s.power[best + 1])
        val offset = if (a - 2 * b + c == 0.0) 0.0 else .5 * (a - c) / (a - 2 * b + c)
        return (best + offset) * s.binHz
    }

    private fun relativeError(a: FloatArray, b: FloatArray): Double {
        assertEquals(a.size, b.size)
        val error = a.indices.sumOf { val delta = a[it] - b[it].toDouble(); delta * delta }
        return sqrt(error / a.sumOf { it.toDouble() * it }.coerceAtLeast(1e-30))
    }

    private fun rms(samples: FloatArray): Double = sqrt(samples.sumOf { it.toDouble() * it } / samples.size)

    private fun matchedDifference(a: FloatArray, b: FloatArray, first: Int, until: Int): Double {
        val ar = sqrt((first until until).sumOf { a[it].toDouble() * a[it] } / (until - first))
        val br = sqrt((first until until).sumOf { b[it].toDouble() * b[it] } / (until - first))
        return sqrt((first until until).sumOf { val delta = a[it] / ar - b[it] / br; delta * delta } / (until - first))
    }

    private fun waveformHash(samples: FloatArray): String {
        val bytes = ByteBuffer.allocate(samples.size * 4).order(ByteOrder.LITTLE_ENDIAN)
        samples.forEach { bytes.putFloat(it) }
        return hex(MessageDigest.getInstance("SHA-256").digest(bytes.array()))
    }

    private fun hex(bytes: ByteArray): String = bytes.joinToString("") { "%02x".format(it.toInt() and 255) }

    companion object {
        private val audio = ConcurrentHashMap<Pair<OrigamiPatch, OrigamiDiagnostic>, FloatArray>()
    }
